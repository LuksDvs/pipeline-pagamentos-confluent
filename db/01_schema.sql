-- Camada 3 (Ingestão): modelo de origem no Postgres.
-- Executar como o dono do banco (PG_ADMIN_USER).
-- Domínio misto: pagamentos com cartão, em que os estabelecimentos são
-- os clientes atendidos por um BPO financeiro.

DROP TABLE IF EXISTS transactions CASCADE;
DROP TABLE IF EXISTS cards CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;
DROP TABLE IF EXISTS merchants CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,          -- PII
    document_cpf  CHAR(11)     NOT NULL,          -- PII
    email         VARCHAR(160) NOT NULL,          -- PII
    city          VARCHAR(80)  NOT NULL,
    created_at    TIMESTAMP(3) NOT NULL DEFAULT now()
);

CREATE TABLE accounts (
    account_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER      NOT NULL REFERENCES customers (customer_id),
    account_type  VARCHAR(20)  NOT NULL,          -- corrente | pagamento | credito
    status        VARCHAR(20)  NOT NULL,          -- ativa | bloqueada
    risk_tier     VARCHAR(10)  NOT NULL,          -- baixo | medio | alto
    credit_limit  NUMERIC(15,2) NOT NULL,
    -- Tempo de evento da versão da conta: é por ele que o Flink faz o
    -- temporal join ("qual era a conta no momento da transação?").
    updated_at    TIMESTAMP(3) NOT NULL DEFAULT now()
);

CREATE TABLE cards (
    card_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    INTEGER      NOT NULL REFERENCES accounts (account_id),
    card_last4    CHAR(4)      NOT NULL,          -- PCI (nunca o número completo)
    brand         VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    issued_at     TIMESTAMP(3) NOT NULL
);

CREATE TABLE merchants (
    merchant_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_name    VARCHAR(120) NOT NULL,
    mcc           CHAR(4)      NOT NULL,          -- categoria do estabelecimento
    city          VARCHAR(80)  NOT NULL,
    bpo_segment   VARCHAR(30)  NOT NULL,          -- carteira do BPO que atende o cliente
    created_at    TIMESTAMP(3) NOT NULL DEFAULT now()
);

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        INTEGER      NOT NULL REFERENCES cards (card_id),
    account_id     INTEGER      NOT NULL REFERENCES accounts (account_id),
    -- merchant_id e amount aceitam nulo de propósito: alguns eventos com
    -- defeito são gerados para testar a quarentena no Flink.
    merchant_id    INTEGER      REFERENCES merchants (merchant_id),
    amount         NUMERIC(15,2),
    currency       CHAR(3)      NOT NULL DEFAULT 'BRL',
    channel        VARCHAR(20)  NOT NULL,         -- pos | ecommerce | app
    status         VARCHAR(20)  NOT NULL,         -- aprovada | negada
    created_at     TIMESTAMP(3) NOT NULL DEFAULT now()
);

CREATE INDEX idx_tx_card_time ON transactions (card_id, created_at);

-- REPLICA IDENTITY FULL: o evento de UPDATE e o de DELETE passam a trazer
-- a linha inteira no campo "before" do envelope do Debezium.
ALTER TABLE customers    REPLICA IDENTITY FULL;
ALTER TABLE accounts     REPLICA IDENTITY FULL;
ALTER TABLE cards        REPLICA IDENTITY FULL;
ALTER TABLE merchants    REPLICA IDENTITY FULL;
ALTER TABLE transactions REPLICA IDENTITY FULL;
